#!/usr/bin/env python3
"""Generate docs/wiki/assets/barker-spiral-sourced.svg (Em, 1 Nov 2026).
Construction: digits 0-9 on a line. Upper semicircles join 9-sum twins (Subdecadence / Lemurian,
syzygies n::9-n); lower semicircles join 10-sum pairs (Decadence / Atlantean, n + (10-n)).
Alternating them traces one inward spiral 0-9-1-8-2-7-3-6-4-5, ending at 5 (5+5 pairs with itself).
Sources: ccru.net Barker Speaks (decadence 10-sum, subdecadence 9-sum, 'seeing between them');
repo lumpenspace/ccru@7c38ad9 syzygies.ts (4::5 innermost curve, 0::9 outermost), zones.ts (zone 5 inner-eye).
Upper/lower placement and the line layout are a reconstruction, not described in the text."""
W,H=900,720; X0,DX,Y=180,60,360
x=lambda n:X0+n*DX
demons={(0,9):'Uttunul',(1,8):'Murrumur',(2,7):'Oddubb',(3,6):'Djynxx',(4,5):'Katak'}
reg={0:'plex',9:'plex',3:'warp',6:'warp'}
col={'plex':'#f472b6','warp':'#34d399','torque':'#60a5fa'}
o=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="DejaVu Sans Mono,monospace">',
 f'<rect width="{W}" height="{H}" fill="#0f172a"/>',
 f'<text x="{W/2}" y="34" fill="#f8fafc" font-size="19" font-weight="bold" text-anchor="middle">Barker Spiral — 9-sum twins (above) and 10-sum pairs (below)</text>',
 f'<text x="{W/2}" y="56" fill="#94a3b8" font-size="12" text-anchor="middle">Spiral path 0→9→1→8→2→7→3→6→4→5 · reconstruction; see barker-spiral.md</text>']
def arc(a,b,up,c,w):
    r=abs(x(b)-x(a))/2; sweep=1 if (x(b)>x(a))==up else 0
    return f'<path d="M{x(a)},{Y} A{r},{r} 0 0 {sweep} {x(b)},{Y}" fill="none" stroke="{c}" stroke-width="{w}"/>'
seq=[0,9,1,8,2,7,3,6,4,5]
for i in range(len(seq)-1):
    a,b=seq[i],seq[i+1]; up=(a+b==9)
    o.append(arc(a,b,up,'#a78bfa' if up else '#fbbf24',3))
    if up:
        k=tuple(sorted((a,b))); r=abs(x(b)-x(a))/2
        o.append(f'<text x="{(x(a)+x(b))/2}" y="{Y-r-6}" fill="#c4b5fd" font-size="12" text-anchor="middle">{k[0]}::{k[1]} {demons[k]}</text>')
    else:
        r=abs(x(b)-x(a))/2
        o.append(f'<text x="{(x(a)+x(b))/2}" y="{Y+r+16}" fill="#fcd34d" font-size="11" text-anchor="middle">{a}+{b}=10</text>')
# 5+5 self-pair (Decadence, scores zero)
o.append(f'<circle cx="{x(5)}" cy="{Y+14}" r="12" fill="none" stroke="#fbbf24" stroke-width="2" stroke-dasharray="3 2"/>')
o.append(f'<text x="{x(5)+14}" y="{Y+34}" fill="#fcd34d" font-size="10">5+5</text>')
for n in range(10):
    c=col[reg.get(n,'torque')]
    o.append(f'<circle cx="{x(n)}" cy="{Y}" r="15" fill="#1e293b" stroke="{c}" stroke-width="2"/>')
    o.append(f'<text x="{x(n)}" y="{Y+5}" fill="#f8fafc" font-size="15" font-weight="bold" text-anchor="middle">{n}</text>')
o.append(f'<text x="20" y="{H-80}" fill="#64748b" font-size="11">0 has no 10-sum partner among 0–9 (pairs with 10)</text>')
ly=H-50
for i,(t,c) in enumerate([('9-sum twin / syzygy (Lemurian, Subdecadence)','#a78bfa'),('10-sum pair (Atlantean, Decadence)','#fbbf24'),('Torque zone','#60a5fa'),('Warp zone','#34d399'),('Plex zone','#f472b6')]):
    yy=ly+(i%3)*16; xx=60 if i<3 else 520
    o.append(f'<rect x="{xx}" y="{yy-9}" width="12" height="10" fill="{c}"/><text x="{xx+18}" y="{yy}" fill="#cbd5e1" font-size="11">{t}</text>')
o.append(f'<text x="{W-10}" y="{H-8}" fill="#475569" font-size="9" text-anchor="end">Sources: ccru.net Barker Speaks; lumpenspace/ccru@7c38ad9 syzygies.ts, zones.ts · generated by scripts/barker_spiral_svg.py</text>')
o.append('</svg>')
open('docs/wiki/assets/barker-spiral-sourced.svg','w').write('\n'.join(o))
